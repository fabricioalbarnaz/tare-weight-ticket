// One-off generator, run manually whenever the logo image changes:
//   npm run generate-logo-bitmap --workspace=@tare/print-bridge
//
// Converts assets/fida-logo-source.jpeg into the raw bytes of an ESC/POS
// "GS v 0" raster bitmap command and writes them, base64-encoded, into
// src/logo-bitmap.generated.ts. escpos.ts imports that generated module
// and concatenates it as-is — no image library ships in print-bridge's
// runtime dependencies, only here in devDependencies, since the logo
// almost never changes and this process runs unattended as a Windows
// service (see CLAUDE.md's "prefer pure-JS dep" / dependency-light
// hardware-integration guidance).
//
// Target bitmap width: 384px (48 bytes), a conservative value that fits
// within both 58mm and 80mm printers at typical 203dpi resolution. The
// installed POS80's actual confirmed usable print width in dots has not
// been validated on-site (same situation as the scale protocol/serial
// field semantics before their on-site confirmation) — see
// docs/plans/2026-11-05-ticket-logo-plan.md and the on-site validation
// checklist this should get added to.

import { Jimp } from 'jimp';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE_IMAGE = path.join(__dirname, '../assets/fida-logo-source.jpeg');
const PREVIEW_IMAGE = path.join(__dirname, '../assets/fida-logo-preview.png');
const OUTPUT_MODULE = path.join(__dirname, '../src/logo-bitmap.generated.ts');

const TARGET_WIDTH_PX = 384;
/** Luminance (0-255) below which a pixel is printed as an ink dot. Tuned
 * by eye against assets/fida-logo-preview.png for this specific logo's
 * colors (green ring/text, gold outline, white background) — re-check
 * the preview after changing the source image. */
const LUMINANCE_THRESHOLD = 170;

function luminance(r, g, b) {
  return 0.299 * r + 0.587 * g + 0.114 * b;
}

async function main() {
  const image = await Jimp.read(SOURCE_IMAGE);
  const scale = TARGET_WIDTH_PX / image.bitmap.width;
  image.resize({ w: TARGET_WIDTH_PX, h: Math.round(image.bitmap.height * scale) });

  const width = image.bitmap.width;
  const height = image.bitmap.height;
  const widthBytes = width / 8;
  if (!Number.isInteger(widthBytes)) {
    throw new Error(`TARGET_WIDTH_PX (${width}) must be a multiple of 8`);
  }

  const raster = Buffer.alloc(widthBytes * height, 0);
  const preview = new Jimp({ width, height, color: 0xffffffff });

  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const { r, g, b } = image.getPixelColor
        ? intToRgba(image.getPixelColor(x, y))
        : intToRgba(image.bitmap.data.readUInt32BE((y * width + x) * 4));
      const isInk = luminance(r, g, b) < LUMINANCE_THRESHOLD;
      if (isInk) {
        const byteIndex = y * widthBytes + (x >> 3);
        raster[byteIndex] |= 0x80 >> (x & 7);
        preview.setPixelColor(0x000000ff, x, y);
      }
    }
  }

  function intToRgba(int) {
    return {
      r: (int >> 24) & 0xff,
      g: (int >> 16) & 0xff,
      b: (int >> 8) & 0xff,
      a: int & 0xff,
    };
  }

  await preview.write(PREVIEW_IMAGE);

  const widthBytesLE = [widthBytes & 0xff, (widthBytes >> 8) & 0xff];
  const heightLE = [height & 0xff, (height >> 8) & 0xff];
  const command = Buffer.concat([
    Buffer.from([0x1d, 0x76, 0x30, 0x00, ...widthBytesLE, ...heightLE]),
    raster,
  ]);

  const moduleSource = `// Generated by scripts/generate-logo-bitmap.mjs from
// assets/fida-logo-source.jpeg — do not edit by hand, re-run the script
// instead. See docs/plans/2026-11-05-ticket-logo-plan.md.
const LOGO_BITMAP_BASE64 =
  '${command.toString('base64')}';

/** Full ESC/POS "GS v 0" raster bitmap command (header + packed pixel
 * data) for the company logo, ready to concatenate as-is. */
export const LOGO_BITMAP_ESCPOS = Buffer.from(LOGO_BITMAP_BASE64, 'base64');
export const LOGO_BITMAP_WIDTH_PX = ${width};
export const LOGO_BITMAP_HEIGHT_PX = ${height};
`;

  await fs.writeFile(OUTPUT_MODULE, moduleSource);

  console.log(`Wrote ${OUTPUT_MODULE} (${width}x${height}px, ${command.length} bytes)`);
  console.log(`Preview: ${PREVIEW_IMAGE}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
